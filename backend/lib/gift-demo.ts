import { createHash, randomBytes, randomUUID, timingSafeEqual } from "node:crypto";
import { z } from "zod";
import { transaction } from "./agent-store";
import { authPool } from "./auth";
import { giftError } from "./gift-store";
export const giftDemoActor = z.enum(["alex", "casey", "jordan"]);
export type GiftDemoActor = z.infer<typeof giftDemoActor>;
export const giftDemoFriends = [{ key: "alex", name: "Alex" }, { key: "casey", name: "Casey" }, { key: "jordan", name: "Jordan" }] as const;
const digest = (s: string) => createHash("sha256").update(s).digest();
export function giftDemoEnabled(request: Request) {
  return process.env.GIFT_DEMO_ENABLED === "true" && ["localhost", "127.0.0.1", "[::1]"].includes(new URL(request.url).hostname);
}
export function giftDemoCookie(request: Request) {
  return request.headers.get("cookie")?.split(";").map(s => s.trim()).find(s => s.startsWith("gift_demo="))?.slice("gift_demo=".length) ?? "";
}
export async function getGiftDemo(request: Request) {
  if (!giftDemoEnabled(request)) giftError("GIFT_DEMO_DISABLED", 404);
  const cookie = giftDemoCookie(request);
  const parts = cookie.split(".");
  if (parts.length !== 2 || !z.uuid().safeParse(parts[0]).success || !/^[A-Za-z0-9_-]{43}$/.test(parts[1])) giftError("GIFT_DEMO_START_REQUIRED", 401);
  const row = (await authPool.query("SELECT * FROM gift_demo_sessions WHERE id=$1 AND expires_at>now()", [parts[0]])).rows[0];
  if (!row || !timingSafeEqual(Buffer.from(row.token_hash, "hex"), digest(parts[1]))) giftError("GIFT_DEMO_START_REQUIRED", 401);
  return row as { id: string; group_id: string; actors: Record<GiftDemoActor, { id: string; name: string }>; expires_at: Date };
}
export async function createGiftDemo(request: Request, reset = false) {
  if (!giftDemoEnabled(request)) giftError("GIFT_DEMO_DISABLED", 404);
  let current: Awaited<ReturnType<typeof getGiftDemo>> | null = null;
  try { current = await getGiftDemo(request); } catch {}
  if (current && !reset) return { session: current, cookie: null };
  return transaction(async c => {
    await c.query("SELECT pg_advisory_xact_lock(hashtext('gift-demo-sessions'))");
    if (current && reset) await c.query("UPDATE gift_demo_sessions SET expires_at=now() WHERE id=$1", [current.id]);
    // All records removed here were generated by this demo, never real accounts.
    const old = (await c.query("SELECT actors FROM gift_demo_sessions WHERE expires_at<=now() FOR UPDATE")).rows;
    for (const row of old) for (const a of Object.values(row.actors) as { id: string }[]) await c.query("DELETE FROM auth_users WHERE id=$1 AND email LIKE 'gift-demo-%@example.invalid'", [a.id]);
    if (+(await c.query("SELECT count(*) FROM gift_demo_sessions WHERE expires_at>now()")).rows[0].count >= 3) giftError("GIFT_DEMO_SESSION_LIMIT", 429);
    const id = randomUUID(), token = randomBytes(32).toString("base64url"), group = randomUUID();
    const actors = Object.fromEntries(giftDemoFriends.map(f => [f.key, { id: randomUUID(), name: f.name }])) as Record<GiftDemoActor, { id: string; name: string }>;
    for (const a of Object.values(actors)) await c.query('INSERT INTO auth_users(id,name,email,"emailVerified","createdAt","updatedAt") VALUES($1,$2,$3,false,now(),now())', [a.id, a.name, `gift-demo-${a.id}@example.invalid`]);
    await c.query("INSERT INTO gift_groups(id,owner_id,recipient,occasion,reserve_cents,invite_hash,revision) VALUES($1,$2,'Sam','Thank Sam for hosting our birthday weekend',1000,$3,1)", [group, actors.alex.id, randomBytes(32).toString("hex")]);
    const notes = { alex: "Sam recently started watercolor painting. A proper paint set and paper would be a thoughtful thank-you.", casey: "Sam loves hiking, but bought a new backpack last week. Avoid buying another backpack.", jordan: "Sam already has several travel mugs. They would appreciate one thoughtful creative gift instead." };
    for (const [i, f] of giftDemoFriends.entries()) {
      const member = randomUUID();
      await c.query("INSERT INTO gift_members(id,group_id,user_id,name,limit_cents) VALUES($1,$2,$3,$4,$5)", [member, group, actors[f.key].id, f.name, [5000, 3000, 2000][i]]);
      await c.query("INSERT INTO gift_messages(id,member_id,role,content) VALUES($1,$2,'user',$3)", [randomUUID(), member, notes[f.key]]);
    }
    const expires = new Date(Date.now() + 8 * 3600000);
    await c.query("INSERT INTO gift_demo_sessions(id,token_hash,group_id,actors,expires_at) VALUES($1,$2,$3,$4,$5)", [id, digest(token).toString("hex"), group, JSON.stringify(actors), expires]);
    return { session: { id, group_id: group, actors, expires_at: expires }, cookie: `${id}.${token}` };
  });
}
export function giftDemoReturnPath(actor: GiftDemoActor) { return `/gifts/demo?friend=${actor}`; }

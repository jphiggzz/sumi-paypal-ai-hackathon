function SidebarMeasuredActiveIndicator({
  activeTarget,
  className,
  containerRef,
  style,
  targetAttribute = "data-sidebar-active-target",
  ...props
}: React.ComponentProps<"span"> & {
  activeTarget: string | null;
  containerRef: React.RefObject<HTMLElement | null>;
  targetAttribute?: string;
}) {
  const [position, setPosition] = React.useState<{
    height: number;
    width: number;
    x: number;
    y: number;
  } | null>(null);

  const updatePosition = React.useCallback(() => {
    const container = containerRef.current;
    if (!container || !activeTarget) {
      setPosition(null);
      return;
    }

    const target = Array.from(
      container.querySelectorAll<HTMLElement>(`[${targetAttribute}]`),
    ).find((element) => element.getAttribute(targetAttribute) === activeTarget);

    if (!target) {
      setPosition(null);
      return;
    }

    const containerRect = container.getBoundingClientRect();
    const targetRect = target.getBoundingClientRect();
    const nextPosition = {
      height: targetRect.height,
      width: targetRect.width,
      x: targetRect.left - containerRect.left,
      y: targetRect.top - containerRect.top,
    };

    setPosition((current) => {
      if (
        current &&
        current.height === nextPosition.height &&
        current.width === nextPosition.width &&
        current.x === nextPosition.x &&
        current.y === nextPosition.y
      ) {
        return current;
      }

      return nextPosition;
    });
  }, [activeTarget, containerRef, targetAttribute]);

  React.useLayoutEffect(() => {
    updatePosition();
  }, [updatePosition]);

  React.useEffect(() => {
    const container = containerRef.current;
    if (!container || !activeTarget) return;

    const target = Array.from(
      container.querySelectorAll<HTMLElement>(`[${targetAttribute}]`),
    ).find((element) => element.getAttribute(targetAttribute) === activeTarget);

    const resizeObserver =
      typeof ResizeObserver === "undefined"
        ? null
        : new ResizeObserver(() => updatePosition());

    resizeObserver?.observe(container);
    if (target) {
      resizeObserver?.observe(target);
    }

    const animationFrame = window.requestAnimationFrame(updatePosition);
    window.addEventListener("resize", updatePosition);
    return () => {
      window.cancelAnimationFrame(animationFrame);
      window.removeEventListener("resize", updatePosition);
      resizeObserver?.disconnect();
    };
  }, [activeTarget, containerRef, targetAttribute, updatePosition]);

  if (!activeTarget) return null;

  return (
    <span
      aria-hidden="true"
      data-active-target={activeTarget}
      data-sidebar="menu-active-indicator"
      data-slot="sidebar-measured-active-indicator"
      className={cn(
        "bg-sidebar-accent pointer-events-none absolute top-0 left-0 z-0 rounded-md opacity-0 transition-[transform,width,height,opacity] duration-200 ease-out motion-reduce:transition-none",
        position && "opacity-100",
        className,
      )}
      style={
        {
          height: position ? `${position.height}px` : 0,
          transform: position
            ? `translate3d(${position.x}px, ${position.y}px, 0)`
            : "translate3d(0, 0, 0)",
          width: position ? `${position.width}px` : 0,
          ...style,
        } as React.CSSProperties
      }
      {...props}
    />
  );
}

